"""Build results/REPORT.md from the CSVs in results/ (spec section 7).

Every number in the report is read from a CSV written by scripts/05_evaluate.py, so the
report can be rebuilt from results/ alone: ``build_report(results_dir)``. Text here
states what the numbers are; it does not add numbers of its own.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd


def _pct(x, d=1):
    return "" if pd.isna(x) else f"{100 * x:.{d}f}%"


def _num(x, d=2):
    return "" if pd.isna(x) else f"{x:.{d}f}"


def md_table(df: pd.DataFrame, fmt: dict | None = None) -> str:
    fmt = fmt or {}
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for rec in df.astype(object).itertuples(index=False):   # keeps ints as ints
        r = dict(zip(cols, rec, strict=True))
        cells = []
        for c in cols:
            v = r[c]
            f = fmt.get(c)
            cells.append(f(v) if f else ("" if pd.isna(v) else str(v)))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def _read(res: Path, name: str) -> pd.DataFrame | None:
    p = res / f"{name}.csv"
    return pd.read_csv(p) if p.exists() else None


PERF_FMT = {"mean_ann": _pct, "geo_ann": _pct, "vol_ann": _pct, "sharpe": _num, "t_nw": _num,
            "max_drawdown": _pct, "hit_rate": _pct, "worst_month": _pct,
            "turnover_month": lambda v: _pct(v)}


def build_report(results_dir) -> str:
    res = Path(results_dir)
    out = ["# HALO capital intensity score: US evaluation report", "",
           "Generated by `scripts/05_evaluate.py` from the CSV files in `results/`. Every number "
           "below is read from one of those files. The holdout is sealed and not included; it "
           "is evaluated once, separately, in M7.", ""]

    s = _read(res, "settings")
    if s is not None:
        out += ["## Design", "", md_table(s), ""]

    out += _holdout_section(res)

    dc = _read(res, "data_checks")
    if dc is not None:
        out += ["## Data checks (each December)", "",
                md_table(dc, {"scored_share": _pct, "link_coverage_top_n": _pct,
                              "missing_next_return_share": lambda v: _pct(v, 2)}), ""]

    perf = _read(res, "perf_summary")
    if perf is not None:
        cols = ["strategy", "months", "mean_ann", "vol_ann", "sharpe", "t_nw", "max_drawdown",
                "hit_rate", "turnover_month"]
        for w in perf["window"].unique():
            t = perf[(perf["window"] == w) & (perf["returns"] == "net")]
            out += [f"## Performance, net of costs: {w}", "",
                    "Long the top score quintile, short the bottom, equal weight, rebalanced "
                    "monthly. `t_nw` is the Newey-West t statistic of the mean.", "",
                    md_table(t[cols], PERF_FMT), ""]
            g = perf[(perf["window"] == w) & (perf["returns"] == "gross")]
            if len(g):
                out += ["Gross of costs:", "", md_table(g[cols], PERF_FMT), ""]

    comp = _read(res, "comparisons")
    rw = _read(res, "random_weights")
    if comp is not None:
        n_rw = f"{len(rw):,}" if rw is not None else "the"
        out += ["## Comparisons the tuned blend must beat (spec 5.5)", "",
                f"Random weightings are {n_rw} fixed Dirichlet(1) blends evaluated on the same "
                "out-of-sample months. A percentile near 50% means tuning did no better than "
                "an arbitrary blend.", "",
                md_table(comp, {"value": lambda v: _num(v, 3)}), ""]

    rc = _read(res, "reality_check")
    trials = _read(res, "trials")
    if rc is not None:
        r = rc.iloc[0]
        out += ["## Multiple testing (spec 5.6)", "",
                f"In-sample, over {int(r['months'])} months and {int(r['grid_points'])} weight "
                f"vectors, the best net Sharpe is {_num(r['best_sharpe'])} at "
                f"{r['best_weights']}. Reality Check p-value (stationary bootstrap, "
                f"{int(r['bootstraps'])} draws, mean block {_num(r['mean_block'], 0)} months): "
                f"{_num(r['p_one_sided'], 3)} one-sided for the best positive Sharpe, "
                f"{_num(r['p_two_sided'], 3)} two-sided for the largest absolute Sharpe "
                f"({_num(r['max_abs_sharpe'])}).", ""]
    if trials is not None:
        kind = trials["kind"] if "kind" in trials else pd.Series("grid", index=trials.index)
        g = trials[kind == "grid"]
        out += [f"Trials logged: {len(g):,} weight-vector evaluations (grid points times "
                f"walk-forward years) across {g['config_hash'].nunique()} tuning "
                f"configuration(s), plus {int((kind == 'robustness').sum())} robustness "
                "configurations.", ""]

    fr = _read(res, "factor_regressions")
    if fr is not None:
        keep = ["strategy", "returns", "model", "months", "alpha_ann", "alpha_t", "b_mktrf",
                "b_hml", "b_cma", "b_umd", "b_d_term", "b_d_def", "r2"]
        keep = [c for c in keep if c in fr]
        out += ["## Factor regressions (spec 7.2)", "",
                "Monthly long-short returns on factor returns. Alpha is annualised; t "
                "statistics use Newey-West errors. FF5+UMD+rates adds monthly changes in the "
                "term spread and the default spread.", "",
                md_table(fr[keep], {"alpha_ann": _pct, "alpha_t": _num, "r2": _num,
                                    **{c: _num for c in keep if c.startswith("b_")}}), ""]

    sp = _read(res, "spanning")
    if sp is not None:
        out += ["## Spanning on Value (HML) and Investment (CMA) (spec 7.3)", "",
                md_table(sp, {c: (_pct if c.startswith("alpha_ann") else _num)
                              for c in sp.columns if c not in ("strategy", "months")}), ""]

    fm = _read(res, "fama_macbeth")
    if fm is not None:
        out += ["## Fama-MacBeth (spec 7.4)", "",
                "Monthly regressions of next-month return on the standardised equal-weight "
                "score, alone and with controls (each winsorised at 1% and 99% per month).", "",
                md_table(fm, {"mean_slope": lambda v: _num(v, 4), "t_nw": _num,
                              "avg_stocks": lambda v: _num(v, 0)}), ""]

    ds = _read(res, "double_sorts")
    if ds is not None:
        out += ["## Double sorts (spec 7.5)", "",
                "Score quintiles within terciles of each control; gross Q5 minus Q1 per "
                "tercile (1 = low) and the average across terciles.", "",
                md_table(ds, {"mean_ann": _pct, "t_nw": _num}), ""]

    sub = _read(res, "subperiods")
    if sub is not None:
        out += ["## Sub-periods (spec 7.6)", "",
                md_table(sub[["strategy", "period", "months", "mean_ann", "vol_ann", "sharpe",
                              "t_nw"]], PERF_FMT), ""]

    rob = _read(res, "robustness")
    if rob is not None:
        out += ["## Robustness (spec 7.8)", "",
                "Each variant changes one setting. The tuned weights are the ones chosen in "
                "the main walk-forward, applied unchanged.", "",
                md_table(rob.drop(columns=["config_hash"]),
                         {"mean_ann": _pct, "sharpe": _num, "t_nw": _num,
                          "alpha_ff5umd_ann": _pct, "alpha_ff5umd_t": _num}), ""]

    co = _read(res, "composition")
    if co is not None and len(co):
        f = co[co["group"] == "ff12"]
        years = sorted(f["year"].unique())
        pick = sorted({years[0], years[len(years) // 2], years[-1]})
        rows = []
        for y in pick:
            for b in ("top", "bottom"):
                g = f[(f["year"] == y) & (f["basket"] == b)].sort_values("share",
                                                                         ascending=False)
                if len(g):
                    rows.append({"year": y, "basket": b, "stocks": int(g["n_stocks"].iloc[0]),
                                 "avg cap $bn": _num(g["avg_cap_bn"].iloc[0], 1),
                                 "largest industries (FF12, share of stocks)": ", ".join(
                                     f"{i} {_pct(v, 0)}" for i, v in
                                     zip(g["industry"].head(3), g["share"].head(3),
                                         strict=True))})
        out += ["## Basket composition (spec 6)", "",
                "How much of the result is a sector bet. Full yearly detail, including "
                "2-digit SIC, is in `results/composition.csv`.", "",
                md_table(pd.DataFrame(rows)), ""]

    charts = sorted((res / "charts").glob("*.png")) if (res / "charts").exists() else []
    if charts:
        out += ["## Charts", ""] + [f"![{c.stem}](charts/{c.name})" for c in charts] + [""]

    out += ["## Limitations", "",
            "- US large and mid caps only; Goldman's study uses the STOXX 600.",
            "- Annual fundamentals with a conservative reporting lag; quarterly data could "
            "update the score sooner.",
            "- Missing intangibles are treated as zero, which matters mainly before the "
            "goodwill accounting change of the early 2000s (see the panel checks).",
            "- Costs are a flat rate per dollar traded; no market-impact model.",
            "- None of the six metrics measures obsolescence; the optional extension is not "
            "included.",
            "- The holdout, including Goldman's 2025 window, is short (a few years of months), "
            "so its statistics are imprecise.", ""]
    return "\n".join(out)


def _holdout_section(res: Path) -> list[str]:
    meta = _read(res, "holdout_meta")
    if meta is None:
        return []
    m = meta.iloc[0]
    out = [f"## Holdout result: {m['holdout_start']} to {m['last_month']} (M7)", ""]
    if bool(m["forced_rerun"]):
        out += ["**WARNING: the holdout was evaluated more than once (rerun with --force). "
                "Treat these numbers with that in mind; see results/holdout_evaluated.lock.**",
                ""]
    out += [f"Evaluated once on {m['evaluated_at_utc']} UTC with config {m['config_hash']}. "
            "The weights were tuned on pre-holdout months only and written to disk before "
            "any holdout return was computed.", ""]
    w = _read(res, "holdout_weights")
    if w is not None:
        cols = ["lambda", *[c for c in w.columns if c.startswith("w_")], "train_start",
                "train_end", "train_months", "in_sample_sharpe_smoothed"]
        out += ["Frozen weights (lambda 1 = tuned, 0 = equal weight):", "",
                md_table(w[cols], {c: lambda v: _num(v, 2) for c in cols
                                   if c.startswith("w_") or c.startswith("in_sample")}), ""]
    g = _read(res, "holdout_goldman")
    if g is not None:
        out += ["Goldman claim check: cumulative top-basket return relative to the bottom "
                "basket since the regime start, gross, on the same axes as Goldman's headline "
                "(which is for Europe, not the US).", "",
                md_table(g, {"top_cumulative": _pct, "bottom_cumulative": _pct,
                             "top_vs_bottom_relative": _pct, "top_vs_universe_relative": _pct,
                             "goldman_reported_europe": lambda v: _pct(v, 0)}), ""]
    hp = _read(res, "holdout_perf")
    if hp is not None:
        cols = ["strategy", "months", "mean_ann", "vol_ann", "sharpe", "t_nw", "max_drawdown",
                "hit_rate", "turnover_month"]
        for win in hp["window"].unique():
            t = hp[(hp["window"] == win) & (hp["returns"] == "net")]
            out += [f"Performance, net of costs: {win}", "", md_table(t[cols], PERF_FMT), ""]
    fr = _read(res, "holdout_factor_regressions")
    if fr is not None:
        keep = [c for c in ["strategy", "model", "months", "alpha_ann", "alpha_t", "b_mktrf",
                            "b_hml", "b_cma", "b_umd", "b_d_term", "b_d_def", "r2"] if c in fr]
        out += ["Holdout factor regressions (net):", "",
                md_table(fr[keep], {"alpha_ann": _pct, "alpha_t": _num, "r2": _num,
                                    **{c: _num for c in keep if c.startswith("b_")}}), ""]
    return out
